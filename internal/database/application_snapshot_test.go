func TestApplicationScoreDetailsAutoGeneratedAndFrozen(t *testing.T) {
	dir := t.TempDir()
	dm := &DBManager{DataDir: dir}
	dm.SetDataKey(make([]byte, 32))
	if err := dm.InitConfigDB(); err != nil {
		t.Fatal(err)
	}
	if err := dm.SaveSchoolConfig("테스트중학교", 1, "", false, 2027); err != nil {
		t.Fatal(err)
	}
	if err := dm.InitClassDB(1); err != nil {
		t.Fatal(err)
	}

	// 1. 학생 초기 성적 및 출결 등록 (만점 성적)
	student := parser.StudentExcelData{
		ClassNum: 1, StudentNum: "1", Name: "홍길동",
		RawData:        `[{"학년":"1","학기":"2","과목":"국어","성취도":"A"},{"학년":"2","학기":"1","과목":"국어","성취도":"A"},{"학년":"2","학기":"2","과목":"국어","성취도":"A"},{"학년":"3","학기":"1","과목":"국어","성취도":"A"}]`,
		AttendanceData: `[{"학년":"1","결석":"0","지각":"0","조퇴":"0","결과":"0"},{"학년":"2","결석":"0","지각":"0","조퇴":"0","결과":"0"},{"학년":"3","결석":"0","지각":"0","조퇴":"0","결과":"0"}]`,
		VolunteerData:  `[{"학년":"1","시간":"15"},{"학년":"2","시간":"15"},{"학년":"3","시간":"15"}]`,
	}
	if err := dm.SaveClassStudents(1, []parser.StudentExcelData{student}); err != nil {
		t.Fatal(err)
	}

	// 2. 울산공업고등학교 일반전형 지원 기록 저장 (ScoreDetails를 명시하지 않아도 자동 산출 및 고정되어야 함)
	appRecord := model.ApplicationRecord{
		ClassNum:      1,
		StudentNum:    "1",
		StudentName:   "홍길동",
		AdmissionYear: 2027,
		Category:      "special",
		SchoolName:    "울산공업고등학교",
		Track:         "일반",
		Status:        "지원 완료",
		Score:         100.0,
		Preferences:   []string{"스마트기계과"},
	}
	if err := dm.SaveApplication(appRecord); err != nil {
		t.Fatalf("SaveApplication: %v", err)
	}

	// 3. 저장된 지원 기록 조회 및 스냅샷 검증
	savedApps, err := dm.GetStudentApplications(1, "1", "홍길동")
	if err != nil || len(savedApps) != 1 {
		t.Fatalf("GetStudentApplications failed: %#v, %v", savedApps, err)
	}
	frozen := savedApps[0]
	if frozen.ScoreDetails == nil {
		t.Fatal("expected ScoreDetails to be auto-generated, got nil")
	}
	originalTotal := frozen.ScoreDetails.TotalScore
	originalAttendance := frozen.ScoreDetails.AttendanceScore
	if originalTotal <= 0 || originalAttendance <= 0 {
		t.Fatalf("unexpected ScoreDetails values: %#v", frozen.ScoreDetails)
	}

	// 4. [불변성 검증] 이후 2학기에 학생의 출결 감점이 발생하거나 학생 정보가 수정되어도
	// 이미 고정된 원서의 ScoreDetails는 절대 변경되지 않아야 함!
	badStudent := student
	badStudent.AttendanceData = `[{"학년":"3","결석":"10","지각":"5","조퇴":"0","결과":"0"}]`
	if _, err := dm.UpdateStudentAttendance(1, []parser.StudentExcelData{badStudent}); err != nil {
		t.Fatal(err)
	}

	// 지원 상태만 '합격'으로 업데이트 (점수 세부정보는 기존 고정값 유지)
	frozen.Status = "합격"
	frozen.ScoreDetails = nil // nil로 보내도 기존 고정 스냅샷이 보존되어야 함
	if err := dm.SaveApplication(frozen); err != nil {
		t.Fatal(err)
	}

	appsAfterUpdate, err := dm.GetStudentApplications(1, "1", "홍길동")
	if err != nil || len(appsAfterUpdate) != 1 {
		t.Fatal(err)
	}
	afterDetail := appsAfterUpdate[0].ScoreDetails
	if afterDetail == nil {
		t.Fatal("ScoreDetails lost after update")
	}
	if afterDetail.TotalScore != originalTotal || afterDetail.AttendanceScore != originalAttendance {
		t.Fatalf("ScoreDetails was modified! original=(total:%f, att:%f), now=(total:%f, att:%f)",
			originalTotal, originalAttendance, afterDetail.TotalScore, afterDetail.AttendanceScore)
	}
}

func TestApplicationScoreDetailsBackfillLegacyRecords(t *testing.T) {
	dir := t.TempDir()
	dm := &DBManager{DataDir: dir}
	dm.SetDataKey(make([]byte, 32))
	if err := dm.InitConfigDB(); err != nil {
		t.Fatal(err)
	}
	if err := dm.SaveSchoolConfig("테스트중학교", 1, "", false, 2027); err != nil {
		t.Fatal(err)
	}
	if err := dm.InitClassDB(1); err != nil {
		t.Fatal(err)
	}

	// 학생 등록
	student := parser.StudentExcelData{
		ClassNum: 1, StudentNum: "2", Name: "이몽룡",
		RawData: `[{"학년":"1","학기":"2","과목":"수학","성취도":"A"}]`,
	}
	if err := dm.SaveClassStudents(1, []parser.StudentExcelData{student}); err != nil {
		t.Fatal(err)
	}

	// 과거 버전처럼 score_details_json이 빈 문자열인 레코드를 강제 삽입
	db, err := dm.OpenDB(dm.GetClassDBPath(1))
	if err != nil {
		t.Fatal(err)
	}
	_, err = db.Exec(`INSERT INTO student_applications (student_num, student_name, admission_year, category, school_name, track, status, score, score_details_json)
		VALUES ('2', '이몽룡', 2027, 'special', '울산공업고등학교', '일반', '합격', 80.0, '')`)
	db.Close()
	if err != nil {
		t.Fatal(err)
	}

	// 백필 실행 전: ScoreDetails가 nil이어야 함
	beforeApps, err := dm.GetStudentApplications(1, "2", "이몽룡")
	if err != nil || len(beforeApps) != 1 || beforeApps[0].ScoreDetails != nil {
		t.Fatalf("expected nil ScoreDetails before backfill, got %#v", beforeApps)
	}

	// 백필 실행 (자가 치유 / 마이그레이션)
	updatedCount, err := dm.BackfillAllApplicationsScoreDetails()
	if err != nil {
		t.Fatalf("BackfillAllApplicationsScoreDetails failed: %v", err)
	}
	if updatedCount != 1 {
		t.Fatalf("expected 1 record backfilled, got %d", updatedCount)
	}

	// 백필 실행 후: 학생 성적으로부터 역산된 ScoreDetails가 채워져 있어야 함
	afterApps, err := dm.GetStudentApplications(1, "2", "이몽룡")
	if err != nil || len(afterApps) != 1 {
		t.Fatal(err)
	}
	if afterApps[0].ScoreDetails == nil {
		t.Fatal("expected ScoreDetails to be populated after backfill, got nil")
	}
	if afterApps[0].ScoreDetails.TotalScore <= 0 {
		t.Fatalf("unexpected backfilled TotalScore: %f", afterApps[0].ScoreDetails.TotalScore)
	}
}
